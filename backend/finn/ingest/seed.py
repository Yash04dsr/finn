def write_snapshot() -> None:
    SNAPSHOT_DIR.mkdir(parents=True, exist_ok=True)
    rows = []
    for i, a in enumerate(ANNOUNCEMENTS):
        rows.append({
            "ticker": a["ticker"],
            "category": a["category"],
            "headline": a["headline"],
            "body": a.get("body", ""),
            "importance": a.get("importance", 3),
            "filed_at": "",  # re-dated at load time
        })
    (SNAPSHOT_DIR / "announcements.json").write_text(json.dumps(rows, indent=1))
    print(f"wrote {len(rows)} snapshot announcements")


if __name__ == "__main__":
    write_snapshot()
